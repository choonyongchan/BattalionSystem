-- Unified schema: one table per kind of data, shared by every company and told apart by a
-- `company` column (lowercase, e.g. 'hercules'): NominalRoll, Exceptions, Duty, Settings,
-- OffLeave, Conducts, ConductDecisions, MedicalReviews, OverviewMarks; PublicHolidays is battalion-wide.
-- Run scripts/sync-schema.ts to apply to the hercules project.
-- Safe to re-run (IF NOT EXISTS, ON CONFLICT DO NOTHING). Structure only: never
-- UPDATE or DELETE existing rows here, as every sync re-runs the whole file on live data.
-- Columns are declared in CREATE TABLE; ALTERs below only migrate tables made by older versions.
-- The old per-company tables ({Company}_Duty, ...) are copied and dropped by scripts/migrate-shared-tables.ts.

GRANT USAGE ON SCHEMA public TO anon, authenticated;

-- Platoon keys come from Settings > Platoons, so no CHECK on platoon
CREATE TABLE IF NOT EXISTS public."NominalRoll" (
  id          uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  company     text NOT NULL CHECK (company = ANY (ARRAY['archer','braves','cougar','stallion','hercules','test'])),
  rank        text NOT NULL,
  name        text NOT NULL,
  platoon     text NOT NULL,
  four_d      text,
  on_strength boolean NOT NULL DEFAULT true,
  bunk        text,
  PRIMARY KEY (company, name)
);
-- id: stable per soldier so exceptions survive a rename; (company, name) stays the key for the upsert-on-name bulk import
-- on_strength false = posted out: hidden from strength and the roll, history kept
-- bunk: label for soldiers whose 4D does not give it (e.g. 'ASA + MEDIC BUNK'); null = read off the 4D

-- soldier_id SET NULL, not CASCADE: clearing the roll before a bulk re-import must not wipe
-- exceptions; they fall back to matching by name. type: the fine-grained kind (MC, LD, ...);
-- scope is the parade section it prints under. revoked_at set = taken back, kept on history.
-- Guard Duty lives in Duty (role duty types), not here.
CREATE TABLE IF NOT EXISTS public."Exceptions" (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company           text NOT NULL CHECK (company = ANY (ARRAY['archer','braves','cougar','stallion','hercules','test'])),
  name              text NOT NULL,
  scope             text NOT NULL CHECK (scope = ANY (ARRAY['Att C','Status','Off/Leave','Guard Duty','Report Sick','MA','Others'])),
  reason            text,
  start             date,
  "end"             date,
  counts_as_absence boolean NOT NULL DEFAULT true,
  time              text,
  location          text,
  in_out            text CHECK (in_out IS NULL OR in_out = ANY (ARRAY['IN','OUT'])),
  soldier_id        uuid REFERENCES public."NominalRoll" (id) ON DELETE SET NULL,
  type              text,
  revoked_at        timestamptz
);
CREATE INDEX IF NOT EXISTS exceptions_company_name_scope_idx ON public."Exceptions" (company, name, scope);
CREATE INDEX IF NOT EXISTS exceptions_soldier_idx ON public."Exceptions" (soldier_id);

-- Duty types come from Settings > Duty Roster, so no CHECK on duty_type
CREATE TABLE IF NOT EXISTS public."Duty" (
  company   text NOT NULL CHECK (company = ANY (ARRAY['archer','braves','cougar','stallion','hercules','test'])),
  duty_type text NOT NULL,
  date      date NOT NULL,
  name      text NOT NULL,
  PRIMARY KEY (company, duty_type, date)
);

CREATE TABLE IF NOT EXISTS public."OffLeave" (
  company text NOT NULL CHECK (company = ANY (ARRAY['archer','braves','cougar','stallion','hercules','test'])),
  name    text NOT NULL,
  off     numeric(5,1) NOT NULL DEFAULT 0 CHECK (off   >= 0 AND off   * 2 = floor(off   * 2)),
  leave   numeric(5,1) NOT NULL DEFAULT 0 CHECK (leave >= 0 AND leave * 2 = floor(leave * 2)),
  PRIMARY KEY (company, name)
);

-- One row per company. The first eight DEFAULTs mirror defaultSettings() in backend/domain/settings/settings.ts.
-- Later columns have no default: null falls back to defaultSettings(company), the only copy.
CREATE TABLE IF NOT EXISTS public."Settings" (
  company                     text PRIMARY KEY CHECK (company = ANY (ARRAY['archer','braves','cougar','stallion','hercules','test'])),
  duty_base_weights           jsonb NOT NULL DEFAULT '{"CDO":1,"CDS":1,"COS":1,"PDS1":1,"PDS2":1,"PDS3":1,"PDS4":1,"Guard Duty":1}',
  duty_day_multipliers        jsonb NOT NULL DEFAULT '{"MonThurs":1,"Friday":1.5,"Saturday":2,"Sunday":1.5,"PublicHoliday":2}',
  duty_weight_exceptions      jsonb NOT NULL DEFAULT '{}',
  eligibility_name_overrides  jsonb NOT NULL DEFAULT '{}',
  eligibility_rank_overrides  jsonb NOT NULL DEFAULT '{}',
  guard_duty_rank_overrides   jsonb NOT NULL DEFAULT '{}',
  absence_scope_defaults      jsonb NOT NULL DEFAULT '{"Att C":true,"Off/Leave":true,"MA":true,"Status":false,"Report Sick":false,"Others":false}',
  parade_times                jsonb NOT NULL DEFAULT '{"First Parade":"09:30","Last Parade":"17:30"}',
  platoons                    jsonb,
  extra_duty_types            jsonb,
  multi_name_duty_types       jsonb,
  report_sick                 jsonb,
  conducts                    jsonb,
  overview                    jsonb,
  in_out_scopes               jsonb
);
INSERT INTO public."Settings" (company) VALUES ('archer'),('braves'),('cougar'),('stallion'),('hercules'),('test') ON CONFLICT (company) DO NOTHING;

CREATE TABLE IF NOT EXISTS public."Conducts" (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company    text NOT NULL CHECK (company = ANY (ARRAY['archer','braves','cougar','stallion','hercules','test'])),
  name       text NOT NULL,
  date       date NOT NULL,
  end_date   date CHECK (end_date IS NULL OR end_date >= date),
  start_time time,
  end_time   time,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS conducts_company_date_idx ON public."Conducts" (company, date);

-- Only manual calls are stored; automatic fall-outs are derived from Exceptions.
-- group_kind: seeded from the Overview when a conduct is created; null for a plain manual call
CREATE TABLE IF NOT EXISTS public."ConductDecisions" (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company       text NOT NULL CHECK (company = ANY (ARRAY['archer','braves','cougar','stallion','hercules','test'])),
  conduct_id    uuid NOT NULL REFERENCES public."Conducts" (id) ON DELETE CASCADE,
  soldier_id    uuid NOT NULL REFERENCES public."NominalRoll" (id) ON DELETE CASCADE,
  participating boolean NOT NULL,
  reason        text,
  group_kind    text CHECK (group_kind = ANY (ARRAY['out-of-camp','to-confirm'])),
  created_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (conduct_id, soldier_id)
);
CREATE INDEX IF NOT EXISTS conduct_decisions_soldier_idx ON public."ConductDecisions" (soldier_id);

-- Hand-marked absences/presences on the Overview, shared by every device. key: soldier id or 'name:NAME'
CREATE TABLE IF NOT EXISTS public."OverviewMarks" (
  company text NOT NULL CHECK (company = ANY (ARRAY['archer','braves','cougar','stallion','hercules','test'])),
  date    date NOT NULL,
  key     text NOT NULL,
  kind    text NOT NULL CHECK (kind = ANY (ARRAY['out','present'])),
  PRIMARY KEY (company, date, key)
);

-- A medical review is a 'Report Sick' exception typed 'Medical Review', so it prints in
-- the parade state; NRIC and appointment details live here, apart
CREATE TABLE IF NOT EXISTS public."MedicalReviews" (
  exception_id bigint PRIMARY KEY REFERENCES public."Exceptions" (id) ON DELETE CASCADE,
  company      text NOT NULL CHECK (company = ANY (ARRAY['archer','braves','cougar','stallion','hercules','test'])),
  nric         text NOT NULL,
  coy          text NOT NULL,
  last_ma      date,
  next_ma      date,
  memo         boolean NOT NULL DEFAULT false,
  remarks      text
);

DO $$
DECLARE
  t text;
BEGIN
  -- Each company's commanders share one login (<company>@40sar.internal); RLS matches the row's company to it
  FOREACH t IN ARRAY ARRAY['NominalRoll','Exceptions','Duty','Settings','OffLeave','Conducts','ConductDecisions','MedicalReviews','OverviewMarks'] LOOP
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO authenticated', t);
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS "authenticated can manage %s" ON public.%I', t, t);
    EXECUTE format(
      'CREATE POLICY "authenticated can manage %s" ON public.%I
       FOR ALL TO authenticated
       USING (auth.email() = company || ''@40sar.internal'')
       WITH CHECK (auth.email() = company || ''@40sar.internal'')',
      t, t);
    -- Realtime: devices refetch when any of these tables change for their company. FULL identity so a
    -- DELETE still carries `company` for the subscription filter
    EXECUTE format('ALTER TABLE public.%I REPLICA IDENTITY FULL', t);
    BEGIN
      EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I', t);
    EXCEPTION WHEN duplicate_object THEN NULL;
    END;
  END LOOP;

  -- Expired exceptions (end date passed) are deleted at 00:00 SGT = 16:00 UTC; rows with no end stay.
  -- Needs the pg_cron extension (enable it in the dashboard); same job name = update in place.
  BEGIN
    PERFORM cron.schedule(
      'purge-exceptions', '0 16 * * *',
      'DELETE FROM public."Exceptions" WHERE "end" < (now() AT TIME ZONE ''Asia/Singapore'')::date');
  EXCEPTION WHEN OTHERS THEN RAISE NOTICE 'purge job not scheduled: %', SQLERRM;
  END;
END;
$$;

CREATE TABLE IF NOT EXISTS public."PublicHolidays" (
  date date PRIMARY KEY,
  name text NOT NULL DEFAULT ''
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public."PublicHolidays" TO authenticated;
ALTER TABLE public."PublicHolidays" ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "authenticated can manage PublicHolidays" ON public."PublicHolidays";
CREATE POLICY "authenticated can manage PublicHolidays" ON public."PublicHolidays"
  FOR ALL TO authenticated
  USING (true)
  WITH CHECK (true);

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;
