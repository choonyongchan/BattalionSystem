-- Unified schema for all companies in one Supabase project.
-- Each company gets prefixed tables: {Company}_NominalRoll, _Exceptions, _Duty, _Settings,
-- _OffLeave, _Conducts, _ConductDecisions, _MedicalReviews; PublicHolidays is shared.
-- Run scripts/sync-schema.ts to apply to the hercules project.
-- Safe to re-run (IF NOT EXISTS, ON CONFLICT DO NOTHING). Structure only: never
-- UPDATE or DELETE existing rows here, as every sync re-runs the whole file on live data.
-- Columns are declared in CREATE TABLE; ALTERs below only migrate tables made by older versions.

GRANT USAGE ON SCHEMA public TO anon, authenticated;

DO $$
DECLARE
  companies text[] := ARRAY['Archer','Braves','Cougar','Stallion','Hercules','Test'];
  tables    text[] := ARRAY['NominalRoll','Exceptions','Duty','Settings','OffLeave','Conducts','ConductDecisions','MedicalReviews'];
  c text;
  t text;
BEGIN
  FOREACH c IN ARRAY companies LOOP

    -- Platoon keys come from Settings > Platoons, so no CHECK on platoon
    EXECUTE format('
      CREATE TABLE IF NOT EXISTS public."%s_NominalRoll" (
        id          uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
        rank        text NOT NULL,
        name        text PRIMARY KEY,
        platoon     text NOT NULL,
        four_d      text,
        on_strength boolean NOT NULL DEFAULT true,
        bunk        text
      )', c);
    -- id: stable per soldier so exceptions survive a rename; name stays the PK for the upsert-on-name bulk import
    -- on_strength false = posted out: hidden from strength and the roll, history kept
    -- bunk: label for soldiers whose 4D does not give it (e.g. ''ASA + MEDIC BUNK''); null = read off the 4D
    EXECUTE format('ALTER TABLE public."%s_NominalRoll" ADD COLUMN IF NOT EXISTS bunk text', c);
    EXECUTE format('ALTER TABLE public."%s_NominalRoll" DROP CONSTRAINT IF EXISTS "%s_NominalRoll_platoon_check"', c, c);

    -- soldier_id SET NULL, not CASCADE: clearing the roll before a bulk re-import must not wipe
    -- exceptions; they fall back to matching by name. type: the fine-grained kind (MC, LD, ...);
    -- scope is the parade section it prints under. revoked_at set = taken back, kept on history.
    EXECUTE format('
      CREATE TABLE IF NOT EXISTS public."%s_Exceptions" (
        id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name              text NOT NULL,
        scope             text NOT NULL CHECK (scope = ANY (ARRAY[''Att C'',''Status'',''Off/Leave'',''Guard Duty'',''Report Sick'',''MA'',''Others''])),
        reason            text,
        start             date,
        "end"             date,
        counts_as_absence boolean NOT NULL DEFAULT true,
        time              text,
        location          text,
        in_out            text CHECK (in_out IS NULL OR in_out = ANY (ARRAY[''IN'',''OUT''])),
        soldier_id        uuid REFERENCES public."%s_NominalRoll" (id) ON DELETE SET NULL,
        type              text,
        revoked_at        timestamptz
      )', c, c);
    EXECUTE format('CREATE INDEX IF NOT EXISTS "%s_exceptions_name_scope_idx" ON public."%s_Exceptions" (name, scope)', c, c);
    EXECUTE format('CREATE INDEX IF NOT EXISTS "%s_exceptions_soldier_idx" ON public."%s_Exceptions" (soldier_id)', c, c);

    -- Duty types come from Settings > Duty Roster, so no CHECK on duty_type
    EXECUTE format('
      CREATE TABLE IF NOT EXISTS public."%s_Duty" (
        duty_type text NOT NULL,
        date      date NOT NULL,
        name      text NOT NULL,
        PRIMARY KEY (duty_type, date)
      )', c);
    EXECUTE format('ALTER TABLE public."%s_Duty" DROP CONSTRAINT IF EXISTS "%s_Duty_duty_type_check"', c, c);

    EXECUTE format('
      CREATE TABLE IF NOT EXISTS public."%s_OffLeave" (
        name  text PRIMARY KEY,
        off   numeric(5,1) NOT NULL DEFAULT 0 CHECK (off   >= 0 AND off   * 2 = floor(off   * 2)),
        leave numeric(5,1) NOT NULL DEFAULT 0 CHECK (leave >= 0 AND leave * 2 = floor(leave * 2))
      )', c);

    -- The first eight DEFAULTs mirror defaultSettings() in backend/domain/settings/settings.ts.
    -- Later columns have no default: null falls back to defaultSettings(company), the only copy.
    EXECUTE format('
      CREATE TABLE IF NOT EXISTS public."%s_Settings" (
        id                          smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
        duty_base_weights           jsonb NOT NULL DEFAULT ''{"CDO":1,"CDS":1,"COS":1,"PDS1":1,"PDS2":1,"PDS3":1,"PDS4":1,"Guard Duty":1}'',
        duty_day_multipliers        jsonb NOT NULL DEFAULT ''{"MonThurs":1,"Friday":1.5,"Saturday":2,"Sunday":1.5,"PublicHoliday":2}'',
        duty_weight_exceptions      jsonb NOT NULL DEFAULT ''{}'',
        eligibility_name_overrides  jsonb NOT NULL DEFAULT ''{}'',
        eligibility_rank_overrides  jsonb NOT NULL DEFAULT ''{}'',
        guard_duty_rank_overrides   jsonb NOT NULL DEFAULT ''{}'',
        absence_scope_defaults      jsonb NOT NULL DEFAULT ''{"Att C":true,"Off/Leave":true,"MA":true,"Status":false,"Guard Duty":false,"Report Sick":false,"Others":false}'',
        parade_times                jsonb NOT NULL DEFAULT ''{"First Parade":"09:30","Last Parade":"17:30"}''
      )', c);
    FOREACH t IN ARRAY ARRAY['platoons','extra_duty_types','multi_name_duty_types','report_sick','conducts','overview'] LOOP
      EXECUTE format('ALTER TABLE public."%s_Settings" ADD COLUMN IF NOT EXISTS %I jsonb', c, t);
    END LOOP;
    EXECUTE format('INSERT INTO public."%s_Settings" (id) VALUES (1) ON CONFLICT (id) DO NOTHING', c);

    EXECUTE format('
      CREATE TABLE IF NOT EXISTS public."%s_Conducts" (
        id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
        name       text NOT NULL,
        date       date NOT NULL,
        end_date   date CHECK (end_date IS NULL OR end_date >= date),
        start_time time,
        end_time   time,
        created_at timestamptz NOT NULL DEFAULT now()
      )', c);
    EXECUTE format('CREATE INDEX IF NOT EXISTS "%s_conducts_date_idx" ON public."%s_Conducts" (date)', c, c);

    -- Only manual calls are stored; automatic fall-outs are derived from Exceptions
    EXECUTE format('
      CREATE TABLE IF NOT EXISTS public."%s_ConductDecisions" (
        id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
        conduct_id    uuid NOT NULL REFERENCES public."%s_Conducts" (id) ON DELETE CASCADE,
        soldier_id    uuid NOT NULL REFERENCES public."%s_NominalRoll" (id) ON DELETE CASCADE,
        participating boolean NOT NULL,
        reason        text,
        created_at    timestamptz NOT NULL DEFAULT now(),
        UNIQUE (conduct_id, soldier_id)
      )', c, c, c);
    EXECUTE format('CREATE INDEX IF NOT EXISTS "%s_conduct_decisions_soldier_idx" ON public."%s_ConductDecisions" (soldier_id)', c, c);

    -- A medical review is a 'Report Sick' exception typed 'Medical Review', so it prints in
    -- the parade state; NRIC and appointment details live here, apart
    EXECUTE format('
      CREATE TABLE IF NOT EXISTS public."%s_MedicalReviews" (
        exception_id bigint PRIMARY KEY REFERENCES public."%s_Exceptions" (id) ON DELETE CASCADE,
        nric         text NOT NULL,
        coy          text NOT NULL,
        last_ma      date,
        next_ma      date,
        memo         boolean NOT NULL DEFAULT false,
        remarks      text
      )', c, c);

    -- Strength overrides were removed from the app
    EXECUTE format('DROP TABLE IF EXISTS public."%s_StrengthOverride"', c);

    -- Each company's commanders share one login; RLS matches on its email
    FOREACH t IN ARRAY tables LOOP
      EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public."%s_%s" TO authenticated', c, t);
      EXECUTE format('ALTER TABLE public."%s_%s" ENABLE ROW LEVEL SECURITY', c, t);
      EXECUTE format('DROP POLICY IF EXISTS "authenticated can manage %s_%s" ON public."%s_%s"', c, t, c, t);
      EXECUTE format(
        'CREATE POLICY "authenticated can manage %s_%s" ON public."%s_%s"
         FOR ALL TO authenticated
         USING (auth.email() = lower(%L) || ''@40sar.internal'')
         WITH CHECK (auth.email() = lower(%L) || ''@40sar.internal'')',
        c, t, c, t, c, c);
    END LOOP;

  END LOOP;
END;
$$;

CREATE TABLE IF NOT EXISTS public."PublicHolidays" (
  date date PRIMARY KEY,
  name text NOT NULL DEFAULT ''
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public."PublicHolidays" TO authenticated;
ALTER TABLE public."PublicHolidays" ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "authenticated can manage PublicHolidays" ON public."PublicHolidays";
CREATE POLICY "authenticated can manage PublicHolidays" ON public."PublicHolidays"
  FOR ALL TO authenticated
  USING (true)
  WITH CHECK (true);

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;
